#Function to add two numbers
def add(x,y):
    return x+y
#Function to sub two numbers
def sub(x,y):
    return x-y
#Function to mul two numbers
def mul(x,y):
    return x*y
#functioon to divide two numbers
def div(x,y):
    if y == 0:
        return "Error:Division by zero"
    return x / y
